/*
 * YT8531C register map.
 *
 * All values are taken from the Motorcomm YT8531(D)H / YT8531(D)C / YT8531P
 * datasheet (DRAFT_05, 2021-09-23).  Registers 0x00..0x1f are the IEEE 802.3
 * clause 22 register space.  Vendor registers live in the extended register
 * space, which is reached through the address/data pair 0x1e/0x1f.  MMD
 * registers are reached through the indirect access pair 0x0d/0x0e.
 *
 * A few registers used by the reference driver are not listed in the public
 * datasheet tables (sleep control 0x27 and RGMII clock gating 0x0c).  They are
 * marked "vendor reference" below and are only touched when the corresponding
 * configuration request is explicitly enabled.
 */

